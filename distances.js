export function areaDistance(a, b) {
  if (!a || !b) return null;
  const x = String(a).trim(), y = String(b).trim();
  if (x.toLowerCase() === y.toLowerCase()) return 0;
  const key = [x, y].sort().join("|");
  if (key in AREA_DIST) return AREA_DIST[key];
  // tolerate different letter-case in saved area names
  const low = key.toLowerCase();
  for (const k in AREA_DIST) if (k.toLowerCase() === low) return AREA_DIST[k];
  return null;
}